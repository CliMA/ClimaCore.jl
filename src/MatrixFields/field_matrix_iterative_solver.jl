import Base.CoreLogging

"""
    PreconditionerAlgorithm

Abstract type for algorithms that approximate a `FieldMatrix` (or something
similar, like a [`LazySchurComplement`](@ref)) with a preconditioner `P` for which
`P * x = b` is inexpensive to solve for `x`. If `P` is a diagonal matrix, then `x`
can be computed as `@. inv(P) * b`; otherwise, the `PreconditionerAlgorithm` must
specify a [`FieldMatrixSolverAlgorithm`](@ref) that can be used to solve
`P * x = b` for `x`. Subtypes: [`MainDiagonalPreconditioner`](@ref),
[`BlockDiagonalPreconditioner`](@ref), [`BlockArrowheadPreconditioner`](@ref),
[`BlockArrowheadSchurComplementPreconditioner`](@ref),
[`WeightedPreconditioner`](@ref), and [`CustomPreconditioner`](@ref).

Every subtype of `PreconditionerAlgorithm` must implement methods for the
following functions:

  - [`solver_algorithm`](@ref).
  - [`lazy_preconditioner`](@ref).
"""
abstract type PreconditionerAlgorithm end

"""
    solver_algorithm(P_alg)

Return a `FieldMatrixSolverAlgorithm` that can be used to solve `P * x = b` for
`x`, where `P` is the preconditioner generated by the `PreconditionerAlgorithm`
`P_alg`. If `P_alg` is `nothing` instead of a `PreconditionerAlgorithm`, or if `P`
is a diagonal matrix (and no solver is required to invert it), this returns
`nothing`.
"""
solver_algorithm(::Nothing) = nothing

is_diagonal(P_alg) = isnothing(solver_algorithm(P_alg))

"""
    lazy_preconditioner(P_alg, A)

Construct a lazy `FieldMatrix` (or a concrete one when possible) that
approximates `A` according to the `PreconditionerAlgorithm` `P_alg`. If `P_alg`
is `nothing` instead of a `PreconditionerAlgorithm`, this returns `one(A)`.
"""
lazy_preconditioner(::Nothing, A::FieldMatrix) = one(A)

"""
    check_preconditioner(P_alg, A, b)

Check that `P` is compatible with `b` in the equation `P * x = b`, where `P` is
the preconditioner generated by the `PreconditionerAlgorithm` `P_alg` for `A`.
If `P_alg` requires a `FieldMatrixSolverAlgorithm` `alg` to solve the equation,
this also calls [`check_field_matrix_solver`](@ref) on `alg`.
"""
function check_preconditioner(P_alg, A, b)
    isnothing(P_alg) && return nothing
    lazy_P = lazy_preconditioner(P_alg, A)
    if is_diagonal(P_alg)
        check_block_diagonal_matrix_has_no_missing_blocks(lazy_P, b)
    else
        check_field_matrix_solver(solver_algorithm(P_alg), lazy_P, b)
    end
end

"""
    lazy_or_concrete_preconditioner(P_alg, A, [pool])

Return the preconditioner `P` from [`lazy_preconditioner`](@ref), with its lazy
entries evaluated into new `Field`s (from the `pool` of temporaries; see
[`run_field_matrix_solver!`](@ref)) when the `PreconditionerAlgorithm` `P_alg` requires a
`FieldMatrixSolverAlgorithm` to invert it (whose solves read `P` on every iteration).
Return `nothing` if `P_alg` is `nothing`.
"""
function lazy_or_concrete_preconditioner(P_alg, A, pool = nothing)
    isnothing(P_alg) && return nothing
    lazy_P = lazy_preconditioner(P_alg, A)
    return is_diagonal(P_alg) ? lazy_P : evaluated(lazy_P, pool)
end

"""
    apply_preconditioner(P_alg, P, Δx, lazy_b, [pool])

Construct a lazy `FieldVectorView` that represents the product `@. inv(P) * b`, where
`lazy_b` is a (possibly lazy) `FieldVectorView` that represents `b`, or, when `P_alg`
requires a solver, store the product in `Δx` (with temporaries from the `pool`; see
[`run_field_matrix_solver!`](@ref)) and return it.
"""
function apply_preconditioner(P_alg, P, Δx, lazy_b, pool = nothing)
    isnothing(P_alg) && return lazy_b
    is_diagonal(P_alg) && return lazy_mul(lazy_inv(P), lazy_b)
    alg = solver_algorithm(P_alg)
    run_field_matrix_solver!(alg, Δx, P, lazy_b, empty_dict(lazy_b), pool)
    return Δx
end

